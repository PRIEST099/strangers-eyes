#!/usr/bin/env node
// benchmark/bench/score-maskexp.mjs: the solid-vs-blur mask experiment (D-174/D-175, PRIV/bench/PROTOCOL.md).
//
//   node benchmark/bench/score-maskexp.mjs PRIV/raw/bench-maskexp-<ts>-live-….json   → benchmark/bench/mask-experiment.md
//   node benchmark/bench/score-maskexp.mjs --self-test
//
// Same clue boxes, two fills: the app's solid fill and a Gaussian blur (what blur-based redaction tools do). Distances are
// recomputed with score-bench's haversine and cross-checked against the page's. Output: counts and rounded distances only.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { median, scoreRuns } from './score-bench.mjs';

const PRIV = '/Users/mac/StrangersEyes-private/bench';
const OUT = fileURLToPath(new URL('./mask-experiment.md', import.meta.url));
const maj = (k, n) => n >= 2 && k >= 2;
const km = (x) => (x === null || x === undefined ? 'n/a' : x === Infinity ? 'no location' : x < 10 ? x.toFixed(1) : String(Math.round(x)));
const kmU = (x) => (x === Infinity || x === null || x === undefined ? km(x) : `${km(x)} km`);

/** Two-sided exact sign test p-value for `pos` successes out of `n` non-tied pairs. */
export function signTest(pos, n) {
  if (!n) return null;
  const c = (k) => { let r = 1; for (let i = 1; i <= k; i++) r = (r * (n - k + i)) / i; return r; };
  const tail = Math.min(pos, n - pos);
  let p = 0;
  for (let k = 0; k <= tail; k++) p += c(k);
  return Math.min(1, (2 * p) / 2 ** n);
}

export function compare(photos) {
  const rows = photos.map((p) => {
    const s = p.solid; const b = p.blur;
    return { id: p.id, types: p.types, s, b,
      sMaj5: maj(s.w5, s.scorable), bMaj5: maj(b.w5, b.scorable), sMaj25: maj(s.w25, s.scorable), bMaj25: maj(b.w25, b.scorable),
      // +1: blur's guess is closer. medianD counts an answered run with no location as +Infinity (score-bench, F-307).
      closer: s.medianD === null || b.medianD === null || s.medianD === b.medianD ? 0 : s.medianD > b.medianD ? 1 : -1,
      stopped: s.refused + b.refused > 0 };
  });
  // Scored pairs: no refusal in either arm (the run stops there, so the arms would be unequal) and >= 2 answered runs each.
  const scorable = rows.filter((r) => !r.stopped && r.s.scorable >= 2 && r.b.scorable >= 2);
  const pairs = scorable.filter((r) => r.closer !== 0);
  const blurCloser = pairs.filter((r) => r.closer > 0).length;
  return {
    rows, n: scorable.length,
    blurOnly5: scorable.filter((r) => r.bMaj5 && !r.sMaj5).length, solidOnly5: scorable.filter((r) => r.sMaj5 && !r.bMaj5).length,
    both5: scorable.filter((r) => r.sMaj5 && r.bMaj5).length,
    blurOnly25: scorable.filter((r) => r.bMaj25 && !r.sMaj25).length, solidOnly25: scorable.filter((r) => r.sMaj25 && !r.bMaj25).length,
    blurCloser, solidCloser: pairs.length - blurCloser, ties: scorable.length - pairs.length, p: signTest(blurCloser, pairs.length),
    medSolid: median(scorable.map((r) => r.s.medianD)), medBlur: median(scorable.map((r) => r.b.medianD)),
    refused: rows.reduce((n, r) => n + r.s.refused + r.b.refused, 0), runs: rows.reduce((n, r) => n + r.s.n + r.b.n, 0),
    excluded: rows.length - scorable.length,
  };
}

export function report(meta, c) {
  const L = [];
  L.push('# Mask experiment: solid fill vs blur over the same clues (D-174)');
  L.push('');
  L.push(`Generated by \`benchmark/bench/score-maskexp.mjs\` (${meta.dates.join(', ')}). Counts and rounded distances only.`);
  L.push('');
  L.push('**Question.** Blur-based redaction tools hide a sign by blurring it. Strangers\' Eyes paints a solid block. Does the blur leave the attacker more to work with?');
  L.push('');
  L.push(`**Method.** The held-out benchmark photos where the attacker cited at least one removable clue (and never refused): ${c.rows.length} photos, ${c.n} scored. For each, the clue boxes it cited (padded 15%) were hidden two ways on the same redacted copy: the app's **solid fill**, and a **Gaussian blur** strong enough that a person can't read the text (sigma = ${meta.sigmaPct}% of the box's shorter side, at least 8 px at 2048 px). Faces are solid in both. \`${meta.model}\` attacked each version ${meta.runs}× (a photo is "within 5 km" if 2 of its answered runs are), interleaved (solid, blur, solid, blur, …). Pre-registered in the private protocol before the run.`);
  L.push('');
  L.push('## Results');
  L.push('');
  L.push('| | Photos |');
  L.push('|---|---|');
  L.push(`| Located within 5 km with **blur** but not with solid (2 of 3 runs) | **${c.blurOnly5}** |`);
  L.push(`| Located within 5 km with **solid** but not with blur | ${c.solidOnly5} |`);
  L.push(`| Located within 5 km either way | ${c.both5} |`);
  L.push(`| Within 25 km with blur but not solid / solid but not blur | ${c.blurOnly25} / ${c.solidOnly25} |`);
  L.push(`| Blur's median guess closer than solid's / farther / tied | ${c.blurCloser} / ${c.solidCloser} / ${c.ties} (sign test p = ${c.p === null ? 'n/a' : c.p.toFixed(2)}) |`);
  L.push(`| Median distance over photos: solid → blur | ${kmU(c.medSolid)} → ${kmU(c.medBlur)} |`);
  L.push(`| Refused runs | ${c.refused} / ${c.runs} |`);
  L.push(`| Photos not scored (a refusal stopped the run, or < 2 answered runs in an arm) | ${c.excluded} |`);
  L.push('');
  L.push('| Photo | Clues hidden | Solid: ≤ 5 km runs, median d | Blur: ≤ 5 km runs, median d |');
  L.push('|---|---|---|---|');
  c.rows.forEach((r, i) => L.push(`| m${String(i + 1).padStart(2, '0')}${r.stopped ? ' (stopped: refusal; not scored)' : ''} | ${r.types.join(', ')} | ${r.s.w5}/${r.s.n}, ${kmU(r.s.medianD)} | ${r.b.w5}/${r.b.n}, ${kmU(r.b.medianD)} |`));
  L.push('');
  L.push('**Limits.** A small set and one model; a different blur strength would give different numbers. This tests the claim behind invariant 6 ("solid fills, never blur"); it does not prove a solid fill hides everything: buildings, landscape and layout stay visible either way.');
  L.push('');
  const text = L.join('\n') + '\n';
  if (/-?\d{1,3}\.\d{4,}/.test(text)) throw new Error('report contains a coordinate-like number; refusing to write it');
  return text;
}

function assert(c, m) { if (!c) throw new Error(`self-test: ${m}`); }
function selfTest() {
  assert(Math.abs(signTest(9, 10) - 22 / 1024) < 1e-9, 'sign test 9/10');
  assert(signTest(5, 10) === 1, 'sign test 5/10');
  const t = { lat: 10, lng: 20 };
  const run = (d) => ({ status: 'ok', latencyMs: 1, dKm: d, parsed: { status: 'ok', hypotheses: [{ lat: 10 + d / 111.195, lng: 20 }] } });
  const c = compare([
    { id: 'a', types: ['street_sign'], solid: scoreRuns([run(50), run(60), run(3)], t), blur: scoreRuns([run(1), run(2), run(70)], t) },
    { id: 'b', types: ['storefront_text'], solid: scoreRuns([run(4), run(4), run(4)], t), blur: scoreRuns([run(4), run(4), run(4)], t) },
  ]);
  assert(c.n === 2 && c.blurOnly5 === 1 && c.solidOnly5 === 0 && c.both5 === 1 && c.blurCloser === 1 && c.ties === 1, 'compare');
  const refused = { status: 'declined', latencyMs: 1, dKm: null, parsed: { status: 'declined' } };
  const noLoc = { status: 'no_location_signal', latencyMs: 1, dKm: null, parsed: { status: 'no_location_signal' } };
  const c2 = compare([
    { id: 'r', types: ['x'], solid: scoreRuns([run(1), run(1)], t), blur: scoreRuns([run(1), refused], t) },
    { id: 'n', types: ['x'], solid: scoreRuns([noLoc, noLoc, run(9)], t), blur: scoreRuns([run(2), run(3), run(4)], t) },
  ]);
  assert(c2.n === 1 && c2.excluded === 1 && c2.blurCloser === 1 && c2.blurOnly5 === 1, 'refusal excluded; no-location counts as farthest');
  report({ dates: ['x'], sigmaPct: 15, model: 'm', runs: 3 }, c);
  console.log('score-maskexp: self-test ok');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--self-test')) { selfTest(); process.exit(0); }
  const files = process.argv.slice(2).filter((x) => !x.startsWith('--'));
  if (!files.length) { console.error('usage: score-maskexp.mjs <raw.json> [more …] | --self-test'); process.exit(2); }
  const [head, ...rows] = readFileSync(`${PRIV}/truth.csv`, 'utf8').trim().split(/\r?\n/);
  const keys = head.split(',');
  const truth = new Map(rows.map((r) => { const o = Object.fromEntries(r.split(',').map((v, i) => [keys[i], v])); return [o.id, { lat: Number(o.lat), lng: Number(o.lng) }]; }));
  const byId = new Map();
  const raws = files.map((f) => JSON.parse(readFileSync(f, 'utf8')));
  for (const raw of raws) {
    if (raw.mode !== 'live' || !raw.fixExp || raw.set !== 'bench') throw new Error('not a live bench mask-experiment run');
    for (const p of raw.photos) if (p.complete && !p.skipped && p.fix && !p.fix.skipped) byId.set(p.id, p);
  }
  const photos = [...byId.values()].sort((x, y) => x.id.localeCompare(y.id)).map((p) => {
    const t = truth.get(p.id);
    if (!t) throw new Error(`no truth for ${p.id}`);
    const fx = p.runs.filter((r) => r.kind === 'fix');
    return { id: p.id, types: [...new Set(p.fix.maskedTypes)], solid: scoreRuns(fx.filter((r) => (r.variant ?? 'solid') === 'solid'), t), blur: scoreRuns(fx.filter((r) => r.variant === 'blur'), t) };
  });
  const last = raws.at(-1);
  // The per-arm run count comes from the data (review F-307), not from metadata.
  const perArm = Math.max(0, ...photos.map((p) => Math.max(p.solid.n, p.blur.n)));
  const text = report({ dates: [...new Set(raws.map((r) => r.startedAt.slice(0, 10)))], sigmaPct: Math.round((last.blurSigmaRatio ?? 0.15) * 100), model: last.primary, runs: perArm }, compare(photos));
  writeFileSync(OUT, text);
  console.log(text);
  console.log(`score-maskexp: wrote ${OUT}`);
}
