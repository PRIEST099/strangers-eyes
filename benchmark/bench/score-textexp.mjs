#!/usr/bin/env node
// benchmark/bench/score-textexp.mjs: the text experiment (D-177, pre-registered in PRIV/bench/PROTOCOL.md).
//
//   node benchmark/bench/score-textexp.mjs PRIV/raw/bench-textexp-<ts>-live-….json   → benchmark/bench/text-experiment.md
//   node benchmark/bench/score-textexp.mjs --self-test
//
// A made-up first name is drawn on a card in a public-place photo. The device's own OCR + vault match either catches it
// or not; then the cloud is asked to transcribe all visible text from four copies: no mask, a light blur, a strong blur
// and the app's solid fill. "Read" = the app's own fuzzy matcher finds the name in the answer. Counts only; no names.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { wilson } from './score-bench.mjs';

const OUT = fileURLToPath(new URL('./text-experiment.md', import.meta.url));
const ARMS = [['none', 'No mask'], ['lightBlur', 'Light blur'], ['strongBlur', 'Strong blur'], ['solid', 'Solid fill (the app)']];
const SIZES = ['small', 'medium', 'large'];
const ci = (k, n) => { const [lo, hi] = wilson(k, n); return lo === null ? 'n/a' : `${Math.round(lo * 100)}–${Math.round(hi * 100)}%`; };
const pct = (k, n) => (n ? `${Math.round((100 * k) / n)}%` : 'n/a');

/** recs: [{ size, caught, skipped, arms: { arm: { status, read } } }] → counts. A photo stopped by a refusal is excluded. */
export function tally(recs) {
  const scored = recs.filter((r) => !r.skipped && ARMS.every(([a]) => r.arms?.[a]?.status === 'ok'));
  const t = { photos: recs.length, scored: scored.length, excluded: recs.length - scored.length,
    caught: scored.filter((r) => r.caught === true).length, arms: {}, bySize: {} };
  for (const [a] of ARMS) t.arms[a] = scored.filter((r) => r.arms[a].read === true).length;
  for (const s of SIZES) {
    const rs = scored.filter((r) => r.size === s);
    t.bySize[s] = { n: rs.length, caught: rs.filter((r) => r.caught === true).length, ...Object.fromEntries(ARMS.map(([a]) => [a, rs.filter((r) => r.arms[a].read === true).length])) };
  }
  return t;
}

export function report(meta, t) {
  const L = [];
  L.push('# Text experiment: can the cloud read a private name? (D-177)');
  L.push('');
  L.push(`Generated by \`benchmark/bench/score-textexp.mjs\` (${meta.dates.join(', ')}). Counts only; the names themselves are not in this file.`);
  L.push('');
  L.push('**Why.** The vault exists to catch private words in a photo: a child\'s name on a bag, an employer on a badge. The geolocation test above can\'t show whether hiding them works, because the attacker prompt is told not to repeat names. So this test asks the cloud directly to transcribe all visible text.');
  L.push('');
  L.push(`**Method (pre-registered).** ${t.photos} benchmark photos, each with one drawn card carrying a made-up first name in capitals (8 small, 8 medium, 8 large: text 1.5%, 2.5% and 4% of the image height). The device first ran the app's own OCR and vault match on the unmasked photo. Then \`${meta.model}\` was asked once per version to "transcribe every piece of readable text" (prompt \`textProbe.dev1\`, no tools; run under the name textProbe.v1 with the same text) on the same ≤ 1536 px copy the app would send, with the card: unmasked, under a light blur (sigma 4% of the card's shorter side), under a strong blur (15%, unreadable to a person), or solid-filled as the app does. Faces are solid in every version. "Read" means the app's own fuzzy matcher finds the name in the answer.`);
  L.push('');
  L.push('## Results');
  L.push('');
  L.push('| | Photos | Share | 95% interval |');
  L.push('|---|---|---|---|');
  L.push(`| **The device's OCR caught the name before anything was sent** | **${t.caught} / ${t.scored}** | ${pct(t.caught, t.scored)} | ${ci(t.caught, t.scored)} |`);
  for (const [a, label] of ARMS) L.push(`| The cloud read the name: ${label} | ${t.arms[a]} / ${t.scored} | ${pct(t.arms[a], t.scored)} | ${ci(t.arms[a], t.scored)} |`);
  L.push('');
  L.push('| Text size | Photos | Device caught | Cloud read: none / light blur / strong blur / solid |');
  L.push('|---|---|---|---|');
  for (const s of SIZES) { const b = t.bySize[s]; L.push(`| ${s} | ${b.n} | ${b.caught} | ${b.none} / ${b.lightBlur} / ${b.strongBlur} / ${b.solid} |`); }
  L.push('');
  if (t.excluded) L.push(`${t.excluded} photo(s) not scored (a refusal, an error, or a face the gate would block).`);
  L.push('');
  L.push('**Limits.** Drawn cards in clean capitals are easier to read than real handwriting or a name at an angle; one model, one call per version. A blur\'s strength decides what survives it; this tests two strengths. The device-side catch uses the same OCR and matcher the app runs before the consent screen.');
  L.push('');
  const text = L.join('\n') + '\n';
  if (/-?\d{1,3}\.\d{4,}/.test(text)) throw new Error('report contains a coordinate-like number; refusing to write it');
  return text;
}

function assert(c, m) { if (!c) throw new Error(`self-test: ${m}`); }
function selfTest() {
  const ok = (read) => ({ status: 'ok', read });
  const recs = [
    { size: 'small', caught: true, arms: { none: ok(true), lightBlur: ok(true), strongBlur: ok(false), solid: ok(false) } },
    { size: 'large', caught: false, arms: { none: ok(true), lightBlur: ok(false), strongBlur: ok(false), solid: ok(false) } },
    { size: 'large', caught: true, skipped: 'refused', arms: { none: { status: 'blocked', read: null } } },
  ];
  const t = tally(recs);
  assert(t.scored === 2 && t.excluded === 1 && t.caught === 1 && t.arms.none === 2 && t.arms.lightBlur === 1 && t.arms.solid === 0, 'tally');
  assert(t.bySize.large.n === 1 && t.bySize.small.lightBlur === 1, 'by size');
  report({ dates: ['x'], model: 'm' }, t);
  console.log('score-textexp: self-test ok');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--self-test')) { selfTest(); process.exit(0); }
  const files = process.argv.slice(2).filter((x) => !x.startsWith('--'));
  if (!files.length) { console.error('usage: score-textexp.mjs <raw.json> | --self-test'); process.exit(2); }
  const raws = files.map((f) => JSON.parse(readFileSync(f, 'utf8')));
  for (const r of raws) if (r.mode !== 'live' || !Array.isArray(r.textExp)) throw new Error('not a live text-experiment run');
  const byId = new Map();
  for (const r of raws) for (const x of r.textExp) if (x.complete) byId.set(x.id, x);
  const t = tally([...byId.values()]);
  const text = report({ dates: [...new Set(raws.map((r) => r.startedAt.slice(0, 10)))], model: raws.at(-1).primary }, t);
  writeFileSync(OUT, text);
  console.log(text);
  console.log(`score-textexp: wrote ${OUT}`);
}
